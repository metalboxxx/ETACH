// Generates app/src/gen/ from the sidecar's exported schemas (S7: deterministic, "\n" endings).
//   ../sidecar/schema/<Model>.json  -> src/gen/schema/<Model>.ts   (json-schema-to-typescript)
//   ../sidecar/schema/openapi.json  -> src/gen/openapi.ts          (openapi-typescript)
// Never hand-edit src/gen; run `npm run gen:types` and commit the result.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(here, "..");
const schemaDir = path.resolve(appDir, "../sidecar/schema");
const outDir = path.join(appDir, "src/gen");
const BANNER = "// GENERATED by `npm run gen:types` from sidecar/schema. Do not edit.\n";

const lf = (s) => s.replace(/\r\n?/g, "\n").trimEnd() + "\n";

await rm(outDir, { recursive: true, force: true });
await mkdir(path.join(outDir, "schema"), { recursive: true });

const files = (await readdir(schemaDir))
  .filter((f) => f.endsWith(".json") && f !== "openapi.json")
  .sort();

const names = [];
for (const file of files) {
  const name = path.basename(file, ".json");
  const schema = JSON.parse(await readFile(path.join(schemaDir, file), "utf8"));
  const ts = await compile(schema, name, {
    bannerComment: "",
    additionalProperties: false,
    unreachableDefinitions: true,
    format: true,
    style: { endOfLine: "lf", singleQuote: false, semi: true, printWidth: 100 },
  });
  await writeFile(path.join(outDir, "schema", `${name}.ts`), lf(BANNER + ts));
  names.push(name);
}

// One namespace per model: the files share $defs (e.g. Question inside Test), so a flat
// re-export would collide. Use `import type { Test } from "@/gen/schema/Test"` or `Schema.Test.Test`.
const index = names.map((n) => `export type * as ${n} from "./${n}";`).join("\n");
await writeFile(path.join(outDir, "schema", "index.ts"), lf(BANNER + index));

const spec = JSON.parse(await readFile(path.join(schemaDir, "openapi.json"), "utf8"));
const ast = await openapiTS(spec, { alphabetize: true });
await writeFile(path.join(outDir, "openapi.ts"), lf(BANNER + astToString(ast)));

console.log(`gen:types: ${names.length} schemas + openapi.ts -> src/gen`);
